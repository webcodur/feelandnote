function apply(folder) {
  const spec = fills[folder]
  const p = path.join(root, folder, 'ranking-data.json')
  const data = JSON.parse(readFileSync(p, 'utf8'))
  const prevBySlug = new Map()
  for (const cat of data.categories ?? []) {
    for (const e of cat.entries ?? []) {
      if (e.celebSlug) prevBySlug.set(e.celebSlug, e)
    }
  }
  data.categories = [{
    name: spec.name,
    entries: spec.rows.map(([name, celebSlug, line, note], i) => {
      const prev = prevBySlug.get(celebSlug) ?? {}
      return {
        rank: i + 1,
        name,
        celebSlug,
        line,
        note,
        ...(prev.avatar ? { avatar: prev.avatar } : {}),
        ...(prev.image ? { image: prev.image } : {}),
      }
    }),
  }]
  writeFileSync(p, JSON.stringify(data, null, 2) + '\n', 'utf8')
  const entries = data.categories[0].entries
  const lined = entries.filter((e) => e.line).length
  const top = entries.slice(0, 3).map((e) => `${e.rank}. ${e.name} — ${e.line}`).join('\n  ')
  console.log(`\n# ${folder}  n=${entries.length}  line=${lined}  cat=${data.categories.length}`)
  console.log(`  ${top}`)
}

for (const folder of Object.keys(fills)) apply(folder)
