// ── DB 대사 키 매핑 ──
// DialogType → celeb_dialogues.lines의 키
const DB_KEY_MAP: Partial<Record<DialogType, string>> = {
  join_accept: 'greeting',
  visitor_arrive: 'greeting',
  battle_win: 'battle_win',
  battle_lose: 'battle_lose',
}

// ── 대화 생성 ──

export function generateDialog(
  type: DialogType,
  char: GameCharacter,
  dialogueLines?: Record<string, string[]> | null,
): DialogEntry {
  let message: string | null = null

  // DB 개인화 대사 우선
  if (dialogueLines) {
    const dbKey = DB_KEY_MAP[type]
    if (dbKey) {
      const lines = dialogueLines[dbKey]
      if (lines && lines.length > 0) {
        message = lines[Math.floor(Math.random() * lines.length)]
      }
    }
  }

  // 톤 기반 폴백
  if (!message) {
    const tone = getSpeechTone(char)
    const templates = TEMPLATES[type][tone]
    message = templates[Math.floor(Math.random() * templates.length)]
  }

  return {
    id: nextDialogId(),
    characterId: char.id,
    characterName: char.nickname,
    avatarUrl: char.avatarUrl,
    message,
    type,
  }
}
