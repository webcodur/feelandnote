// ── 대화 생성 ──

export function generateDialog(
  type: DialogType,
  char: GameCharacter,
): DialogEntry {
  const tone = getSpeechTone(char)
  const templates = TEMPLATES[type][tone]
  const message = templates[Math.floor(Math.random() * templates.length)]

  return {
    id: nextDialogId(),
    characterId: char.id,
    characterName: char.nickname,
    avatarUrl: char.avatarUrl,
    message,
    type,
  }
}
