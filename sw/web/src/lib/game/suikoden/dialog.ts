// 천도 — 인물 대화 시스템

import type { GameCharacter, SpeechTone, DialogType, DialogEntry } from './types'

let dialogIdCounter = 0
function nextDialogId(): string {
  return `dlg_${++dialogIdCounter}_${Date.now()}`
}

// ── 말투 결정 ──
// gender: true=남, false=여, null=불명
// 여성은 기본 gentle, courage>=8이면 commander 유지
// 남성은 기존 로직 유지

export function getSpeechTone(char: GameCharacter): SpeechTone {
  const { virtue, courage } = char.stats
  const isFemale = char.gender === false

  // courage>=8 → commander (성별 무관, 용맹한 무장)
  if (courage >= 8) return 'commander'

  // 여성 분기
  if (isFemale) {
    // 여성 scholar: 지력 기반 책사 유지
    if (char.unitClass === 'strategist') return 'scholar'
    // 나머지 여성 → gentle
    return 'gentle'
  }

  // 남성/불명 분기
  if (virtue >= 8) return 'noble'

  switch (char.unitClass) {
    case 'general': return 'commander'
    case 'strategist': return 'scholar'
    case 'artisan': return 'artisan'
    case 'official': return 'noble'
    case 'artist':
    case 'ranger': return 'free'
    default: return 'free'
  }
}

