const checkOnly = process.argv.includes('--check')
const files = readdirSync(LISTING).filter((f) => f.endsWith('.md'))
const slugs = files.map((f) => f.slice(0, -3))

let applied = 0, missing = []
for (const slug of slugs) {
  const bullets = INSIGHTS[slug]
  if (!bullets) { missing.push(slug); continue }
  if (checkOnly) continue
  const path = resolve(LISTING, `${slug}.md`)
  const text = readFileSync(path, 'utf8')
  const section = `## 시사점\n${bullets.map((b) => `- ${b}`).join('\n')}\n`
  let out
  if (text.includes('## 시사점')) {
    out = text.replace(/## 시사점\n[\s\S]*?(?=\n## |\s*$)/, section.trimEnd() + '\n')
  } else if (text.includes('## 경계·주의')) {
    out = text.replace(/\n?## 경계·주의/, `\n${section}\n## 경계·주의`)
  } else {
    out = text.trimEnd() + '\n\n' + section
  }
  writeFileSync(path, out)
  applied++
}
const extra = Object.keys(INSIGHTS).filter((s) => !slugs.includes(s))
console.log(`적용 ${applied} / 누락 ${missing.length}${missing.length ? ': ' + missing.join(', ') : ''}${extra.length ? ' / 사전에 없는 키: ' + extra.join(', ') : ''}`)
