/** SQL 출력만 한다. 운영 연결·적용·파일 생성은 하지 않는다. */
import { pathToFileURL } from 'node:url'
import { CONTENT_ARRAY_REFERENCES } from '../../sw/web-bo/scripts/figure-books/lib/content-array-references.mjs'

export function contentArrayReferenceMigration() {
  const tables = [...new Set(CONTENT_ARRAY_REFERENCES.map(ref => ref.table))].sort()
  const jsonValue = ref => ref.storage === 'text[]' ? `to_jsonb(t.${ref.column})` : `t.${ref.column}`
  const findReferences = CONTENT_ARRAY_REFERENCES.map(ref => `
  IF EXISTS (SELECT 1 FROM public.${ref.table} t
    CROSS JOIN LATERAL public.content_array_reference_ids(${jsonValue(ref)}, '${ref.shape}') ref(content_id)
    WHERE ref.content_id = OLD.id) THEN
    RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'content is referenced by ${ref.table}.${ref.column}',
      DETAIL = format('content_id=%s', OLD.id), TABLE = '${ref.table}', COLUMN = '${ref.column}',
      CONSTRAINT = 'contents_array_reference_guard';
  END IF;`).join('\n')
  const inputBranches = tables.map(table => {
    const refs = CONTENT_ARRAY_REFERENCES.filter(ref => ref.table === table)
    return `  ${table === tables[0] ? 'IF' : 'ELSIF'} TG_TABLE_NAME = '${table}' THEN
    SELECT coalesce(jsonb_agg(to_jsonb(referenced) ORDER BY content_id, column_name), '[]'::jsonb) INTO refs
    FROM (${refs.map(ref => `SELECT content_id, '${ref.column}'::text AS column_name FROM public.content_array_reference_ids(row_json->'${ref.column}', '${ref.shape}') content_id`).join('\n      UNION\n      ')}) referenced;`
  }).join('\n')
  const triggers = tables.map(table => {
    const columns = CONTENT_ARRAY_REFERENCES.filter(ref => ref.table === table).map(ref => ref.column).join(', ')
    return `CREATE TRIGGER ${table}_content_array_reference_guard
  BEFORE INSERT OR UPDATE OF ${columns} ON public.${table}
  FOR EACH ROW EXECUTE FUNCTION public.check_content_array_references();`
  }).join('\n')
  const validation = CONTENT_ARRAY_REFERENCES.map(ref => `
  IF EXISTS (SELECT 1 FROM public.${ref.table} t
    CROSS JOIN LATERAL public.content_array_reference_ids(${jsonValue(ref)}, '${ref.shape}') ref(content_id)
    LEFT JOIN public.contents c ON c.id = ref.content_id WHERE c.id IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'existing missing content in ${ref.table}.${ref.column}';
  END IF;`).join('\n')
  return `-- Generated by scripts/oracle-db/content-array-reference.mjs from CONTENT_ARRAY_REFERENCES.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
LOCK TABLE public.contents, ${tables.map(table => `public.${table}`).join(', ')} IN SHARE ROW EXCLUSIVE MODE;

CREATE FUNCTION public.content_array_reference_ids(value jsonb, shape text)
RETURNS SETOF text LANGUAGE plpgsql IMMUTABLE SET search_path = pg_catalog, public AS $function$
DECLARE entry jsonb; tier jsonb;
BEGIN
  IF value IS NULL OR value = 'null'::jsonb THEN RETURN; END IF;
  IF shape = 'tiers' THEN
    IF jsonb_typeof(value) <> 'object' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'content tiers must be an object of ID arrays';
    END IF;
    FOR tier IN SELECT v FROM jsonb_each(value) AS t(k, v) LOOP
      RETURN QUERY SELECT * FROM public.content_array_reference_ids(tier, 'array');
    END LOOP;
    RETURN;
  END IF;
  IF shape <> 'array' OR jsonb_typeof(value) <> 'array' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'content IDs must be an array';
  END IF;
  FOR entry IN SELECT v FROM jsonb_array_elements(value) AS t(v) LOOP
    IF jsonb_typeof(entry) <> 'string' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'content ID array members must be strings';
    END IF;
    RETURN NEXT entry #>> '{}';
  END LOOP;
END;
$function$;

CREATE FUNCTION public.check_content_array_references()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public SET row_security = off AS $function$
DECLARE row_json jsonb := to_jsonb(NEW); refs jsonb; ref record;
BEGIN
${inputBranches}
  ELSE RAISE EXCEPTION 'unsupported content reference table: %', TG_TABLE_NAME;
  END IF;
  FOR ref IN SELECT * FROM jsonb_to_recordset(refs) AS r(content_id text, column_name text) LOOP
    PERFORM 1 FROM public.contents c WHERE c.id = ref.content_id FOR KEY SHARE;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'array references a missing content',
        DETAIL = format('content_id=%s', ref.content_id), TABLE = TG_TABLE_NAME, COLUMN = ref.column_name,
        CONSTRAINT = TG_TABLE_NAME || '_content_array_reference_guard';
    END IF;
  END LOOP;
  RETURN NEW;
END;
$function$;

CREATE FUNCTION public.lock_content_array_references_for_identity_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public SET row_security = off AS $function$
BEGIN
  LOCK TABLE ${tables.map(table => `public.${table}`).join(', ')} IN SHARE ROW EXCLUSIVE MODE;
  RETURN NULL;
END;
$function$;

CREATE FUNCTION public.reject_referenced_content_identity_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public SET row_security = off AS $function$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF OLD.id IS NOT DISTINCT FROM NEW.id THEN RETURN NEW; END IF;
  END IF;
  -- A fixed transaction snapshot can miss a reference committed after it began.
  -- Retry an identity change in READ COMMITTED; unchanged IDs remain allowed.
  IF current_setting('transaction_isolation') NOT IN ('read committed', 'read uncommitted') THEN
    RAISE EXCEPTION USING ERRCODE = '40001', MESSAGE = 'content identity change requires READ COMMITTED',
      HINT = 'Retry the identity change transaction with READ COMMITTED isolation.';
  END IF;
${findReferences}
  IF TG_OP = 'UPDATE' THEN RETURN NEW; END IF;
  RETURN OLD;
END;
$function$;

DO $validation$
BEGIN
${validation}
END;
$validation$;

${triggers}
CREATE TRIGGER contents_array_reference_identity_lock
  BEFORE DELETE OR UPDATE OF id ON public.contents FOR EACH STATEMENT
  EXECUTE FUNCTION public.lock_content_array_references_for_identity_change();
CREATE TRIGGER contents_array_reference_identity_guard
  BEFORE DELETE OR UPDATE OF id ON public.contents FOR EACH ROW
  EXECUTE FUNCTION public.reject_referenced_content_identity_change();
COMMIT;
`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.stdout.write(contentArrayReferenceMigration())
}
