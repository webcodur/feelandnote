import type { GameCharacter, SpeechTone, DialogType, DialogEntry } from './types'

let dialogIdCounter = 0
function nextDialogId(): string {
  return `dlg_${++dialogIdCounter}_${Date.now()}`
}

// ── 말투 결정 ──
// gender: true=남, false=여, null=불명

function getSpeechTone(char: GameCharacter): SpeechTone {
  const { benevolence, courage } = char.stats
  const isFemale = char.gender === false

  // courage>=80 → bold (성별 무관)
  if (courage >= 80) return 'bold'

  // 여성 분기
  if (isFemale) {
    if (char.unitClass === 'strategist') return 'composed'
    return 'gentle'
  }

  // 남성/불명 분기
  if (benevolence >= 80) return 'humble'

  switch (char.unitClass) {
    case 'general': return 'loyal'
    case 'saint': return 'humble'
    case 'strategist': return 'composed'
    case 'artisan': return 'composed'
    case 'official': return 'humble'
    case 'artist':
    case 'ranger': return 'free'
    default: return 'free'
  }
}

