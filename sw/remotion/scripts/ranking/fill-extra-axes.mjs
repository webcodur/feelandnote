function apply(folder) {
  const spec = extras[folder]
  const p = path.join(root, folder, 'ranking-data.json')
  const data = JSON.parse(readFileSync(p, 'utf8'))
  if (!data.categories?.[0]) throw new Error(`${folder}: 1축 없음`)
  const first = data.categories[0]
  const media = new Map()
  for (const e of first.entries ?? []) {
    if (!e.celebSlug) continue
    media.set(e.celebSlug, { avatar: e.avatar, image: e.image })
  }
  const added = spec.map((cat) => ({
    name: cat.name,
    entries: cat.rows.map(([name, celebSlug, line, note], i) => {
      const prev = media.get(celebSlug) ?? {}
      return {
        rank: i + 1,
        name,
        celebSlug,
        line,
        note,
        ...(prev.avatar ? { avatar: prev.avatar } : {}),
        ...(prev.image ? { image: prev.image } : {}),
      }
    }),
  }))
  data.categories = [first, ...added]
  writeFileSync(p, JSON.stringify(data, null, 2) + '\n', 'utf8')
  const ns = data.categories.map((c) => `${c.name} ${c.entries.length}`).join(' · ')
  console.log(`${folder}  ${ns}`)
}

for (const folder of Object.keys(extras)) apply(folder)
